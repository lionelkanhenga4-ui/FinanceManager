create extension if not exists pgcrypto;

create table if not exists public.accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  balance numeric(12, 2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  amount numeric(12, 2) not null check (amount > 0),
  type text not null check (type in ('income', 'expense')),
  income boolean not null,
  category_name text not null default 'Other',
  account_id uuid references public.accounts(id) on delete set null,
  date bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  created_at timestamptz not null default now(),
  constraint transactions_type_income_match check (income = (type = 'income'))
);

alter table public.accounts add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.accounts add column if not exists name text;
alter table public.accounts add column if not exists balance numeric(12, 2) not null default 0;
alter table public.transactions add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.transactions add column if not exists title text;
alter table public.transactions add column if not exists amount numeric(12, 2) not null default 0;
alter table public.transactions add column if not exists type text;
alter table public.transactions add column if not exists income boolean not null default false;
alter table public.transactions add column if not exists category_name text not null default 'Other';
alter table public.transactions add column if not exists account_id uuid;
alter table public.transactions add column if not exists date bigint;
alter table public.transactions add column if not exists created_at timestamptz not null default now();

do $$
declare
  existing_date_type text;
begin
  select data_type into existing_date_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'transactions'
    and column_name = 'date';

  if existing_date_type in ('timestamp with time zone', 'timestamp without time zone', 'date') then
    alter table public.transactions
      alter column date type bigint
      using ((extract(epoch from date)::numeric * 1000)::bigint);
  end if;
end $$;

update public.transactions
set type = case when income then 'income' else 'expense' end
where type is null or type not in ('income', 'expense');

update public.transactions
set income = (type = 'income')
where income is distinct from (type = 'income');

update public.transactions
set date = (extract(epoch from created_at) * 1000)::bigint
where date is null;

alter table public.transactions alter column type set default 'expense';
alter table public.transactions alter column type set not null;
alter table public.transactions alter column date set default ((extract(epoch from now()) * 1000)::bigint);
alter table public.transactions alter column date set not null;

create index if not exists accounts_user_id_idx on public.accounts(user_id);
create index if not exists transactions_user_id_date_idx on public.transactions(user_id, date desc);

alter table public.accounts enable row level security;
alter table public.transactions enable row level security;

drop policy if exists "Finance users read own accounts" on public.accounts;
create policy "Finance users read own accounts"
on public.accounts for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Finance users manage own accounts" on public.accounts;
create policy "Finance users manage own accounts"
on public.accounts for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Finance users read own transactions" on public.transactions;
create policy "Finance users read own transactions"
on public.transactions for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Finance users insert own transactions" on public.transactions;
create policy "Finance users insert own transactions"
on public.transactions for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Finance users update own transactions" on public.transactions;
create policy "Finance users update own transactions"
on public.transactions for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Finance users delete own transactions" on public.transactions;
create policy "Finance users delete own transactions"
on public.transactions for delete to authenticated
using (auth.uid() = user_id);

grant select, insert, update, delete on public.accounts to authenticated;
grant select, insert, update, delete on public.transactions to authenticated;
grant usage, select on all sequences in schema public to authenticated;
